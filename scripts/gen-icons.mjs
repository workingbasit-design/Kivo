/**
 * Generates src/components/icons/phosphor.tsx from Phosphor Icons SVGs.
 *
 * Part B (dashboard rebuild): one icon family app-wide. Phosphor Icons are
 * ISC licensed (see docs/LICENSES.md). We vendor only the icons the app
 * uses (regular weight for inactive, duotone for active/status) so the
 * bundle carries no icon font and no new npm dependency.
 *
 * Usage: node scripts/gen-icons.mjs
 * Reads the lucide->phosphor map from scripts/icon-map.json.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const map = JSON.parse(readFileSync(join(root, 'scripts', 'icon-map.json'), 'utf8'));

/** Phosphor icons that also need the duotone (outline + soft fill) layer. */
const DUOTONE = new Set([
  'sun', 'calendar-blank', 'toolbox', 'wallet', 'list',
  'warning', 'warning-circle', 'bell', 'bell-ringing', 'clock', 'check-circle',
  'info', 'x-circle', 'broom', 'flame', 'drop', 'plus-circle', 'calendar-check',
  'calendar-x', 'currency-dollar', 'receipt', 'chat-circle', 'map-pin', 'users',
  'magnifying-glass', 'seal-check', 'calendar', 'house',
]);

const BASE = 'https://cdn.jsdelivr.net/npm/@phosphor-icons/core@2.1.1/assets';

async function fetchSvg(kind, name) {
  const suffix = kind === 'duotone' ? '-duotone' : '';
  const url = `${BASE}/${kind}/${name}${suffix}.svg`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  return res.text();
}

/** Extract inner SVG content (everything inside the outer <svg>). */
function inner(svg) {
  const m = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/);
  if (!m) throw new Error('no svg body');
  return m[1].trim();
}

/** Split duotone inner content into soft-fill paths vs outline paths. */
function splitDuotone(body) {
  const fill = [];
  const stroke = [];
  // Paths/groups carrying opacity="0.2" are the soft-fill layer.
  const re = /<(path|g|circle|rect|ellipse|polygon|polyline)\b[^>]*opacity="0\.2"[^>]*>(?:<\/\1>)?|<[^>]+\/>/g;
  let last = 0;
  let m;
  // Simpler: walk top-level elements.
  const els = body.match(/<(path|circle|rect|ellipse|polygon|polyline)[^>]*(?:\/>|>[\s\S]*?<\/\1>)/g) || [];
  for (const el of els) {
    if (/opacity="0\.2"/.test(el)) fill.push(el);
    else stroke.push(el);
  }
  return { fill: fill.join('\n    '), stroke: stroke.join('\n    ') };
}

function pascal(name) {
  return name.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
}

const out = [];
out.push(`/**`);
out.push(` * GENERATED by scripts/gen-icons.mjs - do not edit by hand.`);
out.push(` * Phosphor Icons (ISC licence, see docs/LICENSES.md). Only the icons the`);
out.push(` * app uses are vendored: regular weight for inactive, duotone for`);
out.push(` * active/status. Run \`node scripts/gen-icons.mjs\` to regenerate.`);
out.push(` */`);
out.push(`import React from 'react';`);
out.push(``);
out.push(`export interface IconProps {`);
out.push(`  size?: number | string;`);
out.push(`  className?: string;`);
out.push(`  /** 'regular' (outline) for inactive, 'duotone' (outline + soft fill) for active/status. */`);
out.push(`  weight?: 'regular' | 'duotone';`);
out.push(`  /** Lucide-compat: stroke width on the 24-grid; mapped to Phosphor's 256-grid. */`);
out.push(`  strokeWidth?: number | string;`);
out.push(`  style?: React.CSSProperties;`);
out.push(`  [key: string]: unknown;`);
out.push(`}`);
out.push(``);
out.push(`function PhIcon({`);
out.push(`  size = 24,`);
out.push(`  className,`);
out.push(`  weight = 'regular',`);
out.push(`  strokeWidth,`);
out.push(`  children,`);
out.push(`  duotoneFill,`);
out.push(`  ...rest`);
out.push(`}: IconProps & { children: React.ReactNode; duotoneFill?: React.ReactNode }) {`);
out.push(`  // Phosphor's native regular stroke is 16 on the 256 grid. A lucide-style`);
out.push(`  // strokeWidth prop (24-grid) is scaled up so explicit widths keep working.`);
out.push(`  const sw = strokeWidth != null ? (Number(strokeWidth) * 256) / 24 : 16;`);
out.push(`  return (`);
out.push(`    <svg`);
out.push(`      width={size}`);
out.push(`      height={size}`);
out.push(`      viewBox="0 0 256 256"`);
out.push(`      fill="none"`);
out.push(`      stroke="currentColor"`);
out.push(`      strokeWidth={sw}`);
out.push(`      strokeLinecap="round"`);
out.push(`      strokeLinejoin="round"`);
out.push(`      className={className}`);
out.push(`      aria-hidden={(rest['aria-hidden'] as boolean | 'true' | 'false' | undefined) ?? true}`);
out.push(`      {...rest}`);
out.push(`    >`);
out.push(`      {weight === 'duotone' && duotoneFill ? (`);
out.push(`        <g fill="currentColor" stroke="none" opacity={0.2}>`);
out.push(`          {duotoneFill}`);
out.push(`        </g>`);
out.push(`      ) : null}`);
out.push(`      {children}`);
out.push(`    </svg>`);
out.push(`  );`);
out.push(`}`);
out.push(``);

const names = [...new Set(Object.values(map))].sort();
let ok = 0;
for (const name of names) {
  const regularBody = inner(await fetchSvg('regular', name));
  let duoFill = null;
  if (DUOTONE.has(name)) {
    try {
      const { fill } = splitDuotone(inner(await fetchSvg('duotone', name)));
      duoFill = fill || null;
    } catch (err) {
      console.warn(`duotone missing for ${name}: ${err.message}`);
    }
  }
  const comp = `${pascal(name)}Icon`;
  out.push(`const ${comp}Paths = (`);
  out.push(`  <>`);
  for (const line of regularBody.split('\n')) out.push(`    ${line.trim()}`);
  out.push(`  </>`);
  out.push(`);`);
  if (duoFill) {
    out.push(`const ${comp}DuoFill = (`);
    out.push(`  <>`);
    for (const line of duoFill.split('\n')) out.push(`    ${line.trim()}`);
    out.push(`  </>`);
    out.push(`);`);
  }
  out.push(`export function ${comp}(props: IconProps) {`);
  out.push(`  return (`);
  out.push(`    <PhIcon${duoFill ? ` duotoneFill={${comp}DuoFill}` : ''} {...props}>`);
  out.push(`      {${comp}Paths}`);
  out.push(`    </PhIcon>`);
  out.push(`  );`);
  out.push(`}`);
  out.push(``);
  ok++;
}

const dest = join(root, 'src', 'components', 'icons', 'phosphor.tsx');
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, out.join('\n'));
console.log(`wrote ${dest} with ${ok} icons`);
